import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const out = join(root, "dist-dashboard", "mcp.html");
const modulePath = join(root, "src", "dashboard-html.generated.ts");
const source = join(root, "ui", "dashboard");

function replaceOnce(html, tag, replacement) {
  const parts = html.split(tag);
  if (parts.length !== 2) throw new Error(`Expected exactly one ${tag}`);
  return parts[0] + replacement + parts[1];
}

async function bundledLicenses(inputs) {
  const packages = new Map();
  for (const input of Object.keys(inputs)) {
    let dir = dirname(resolve(root, input));
    while (dir.includes(`${sep}node_modules${sep}`)) {
      const manifest = await readFile(join(dir, "package.json"), "utf8").catch((error) => {
        if (error.code === "ENOENT") return null;
        throw error;
      });
      if (manifest) {
        const { name, version } = JSON.parse(manifest);
        if (name && version) { packages.set(`${name}@${version}`, dir); break; }
      }
      const parent = dirname(dir);
      if (parent === dir) break;
      dir = parent;
    }
  }
  const entries = [];
  for (const [name, dir] of [...packages].sort(([a], [b]) => a.localeCompare(b, "en"))) {
    const files = (await readdir(dir)).filter((file) => /^(license|copying|notice)(\.|$)/i.test(file)).sort();
    if (!files.length) throw new Error(`Bundled package ${name} has no license file at ${dir}`);
    for (const file of files) entries.push(`${name} - ${file}\n${await readFile(join(dir, file), "utf8")}`);
  }
  return entries.join("\n\n").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export async function buildDashboardHtml() {
  const [template, css, result] = await Promise.all([
    readFile(join(source, "index.html"), "utf8"),
    readFile(join(source, "src", "styles.css"), "utf8"),
    build({
      entryPoints: [join(source, "src", "main.tsx")], bundle: true, write: false,
      format: "esm", platform: "browser", target: "es2022", minify: true,
      jsx: "automatic", define: { "process.env.NODE_ENV": '"production"' },
      legalComments: "inline", metafile: true, logLevel: "warning",
    }),
  ]);
  if (result.warnings.length || result.outputFiles.length !== 1) throw new Error("Unexpected dashboard bundle output");
  if (/<\/style/i.test(css)) throw new Error("Unsafe style content");
  const parsedCss = await transform(css, { loader: "css", logLevel: "silent" });
  if (parsedCss.warnings.length) throw new Error(`Invalid dashboard CSS: ${parsedCss.warnings.map((warning) => warning.text).join("; ")}`);
  const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  if (js.includes("<!--")) throw new Error("Unsafe script content");
  await transform(js, { loader: "js", format: "esm" });
  const notices = await bundledLicenses(result.metafile.inputs);
  const html = replaceOnce(replaceOnce(template, '<link rel="stylesheet" href="/assets/dashboard.css" />', `<style>${css}</style>`),
    '<script type="module" src="/assets/dashboard.js"></script>', `<script type="module">${js}</script>`);
  return replaceOnce(html, "</body>", `<template id="dashboard-third-party-licenses">${notices}</template>\n</body>`).replace(/\r\n/g, "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const html = await buildDashboardHtml();
  const moduleSource = `// Generated by scripts/build-dashboard-ui.mjs. Do not edit.\nexport const dashboardHtml = ${JSON.stringify(html)};\n`;
  if (process.argv.includes("--check")) {
    const actual = await readFile(modulePath, "utf8").catch(() => null);
    if (actual !== moduleSource) throw new Error("Dashboard HTML module is stale. Run npm run build:dashboard.");
    if (await readFile(out, "utf8").catch(() => null) !== html) throw new Error("Dashboard HTML is stale. Run npm run build:dashboard.");
    console.log("Dashboard HTML module is up to date.");
  } else {
    await mkdir(dirname(out), { recursive: true });
    await Promise.all([writeFile(out, html), writeFile(modulePath, moduleSource)]);
    console.log(`dist-dashboard/mcp.html and src/dashboard-html.generated.ts (${Buffer.byteLength(html)} bytes)`);
  }
}
